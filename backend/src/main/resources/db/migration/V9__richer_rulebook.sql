-- =============================================================================
-- V9 A rulebook worth retrieving from.
--
-- V7 proved retrieval works with eleven passages. Eleven passages do not answer
-- the questions a member actually asks: nobody asks "what is a listing", they
-- ask "what happens if the lister never confirms", "who moves first at
-- delivery", "can I pledge an inventory note". Each of those is a paragraph
-- somewhere in a venue's published rules, and the advisor can only cite what
-- was ingested.
--
-- So this migration grows the corpus from 11 passages in 4 documents to 77
-- passages in 15, covering trading, delivery, quality, contracts, settlement,
-- membership, inventory notes, breach handling, fees and a member-facing guide.
--
-- Four rules were followed writing the text, and they are worth stating because
-- a rulebook that breaks them is worse than a small one:
--
--   1. Every passage stands alone. It is retrieved without its neighbours and
--      pasted into a prompt, so "如上所述" or "第 X 条" is unusable.
--   2. Consistency with V7 and with the software. Where the code decides
--      something — who confirms, who may start delivery, what a withdrawal is
--      blocked by — the text says the same thing. An advisor confidently
--      quoting a rule the platform does not implement is worse than silence.
--   3. Passages are 150-400 characters. Long enough to carry an answer, short
--      enough that four fit in a prompt. Boilerplate repeated across passages
--      makes every passage match every question, which defeats the ranking.
--   4. New documents extend V7's rather than restating it. RULE-TRADING keeps
--      its four passages; the detail lives in RULE-LISTING, RULE-ORDER and the
--      rest, so a question about withdrawal returns the passage about
--      withdrawal and not the one about what a listing is.
--
-- Retrieval note, because it shapes the wording: the keyword half of the hybrid
-- search is a FULLTEXT index with the ngram parser at ngram_token_size = 2, so
-- only 2-character sequences are indexed. A query is tokenised the same way,
-- which means a passage ranks for a question when it literally contains the
-- question's bigrams — "磅差怎么算" reaches the passage containing 磅差, and a
-- passage that never writes 磅差 is invisible to it however well it paraphrases
-- the idea. Terminology is therefore repeated deliberately: 磅差, 保证金比例,
-- 电子库存单, 质押 and 交收 each appear in the passages that answer for them.
--
-- Ids continue V7's small literals: 4005-4015 for documents (V7 used 4001-4004)
-- and 4120-4185 for chunks (V7 used 4101-4111). Both stay far below the
-- snowflake range the application assigns, and clear of the 7xxx/9xxx blocks
-- the demo-data scripts use.
--
-- Embeddings are deliberately not written here. They come from the local Ollama
-- model at runtime through POST /api/knowledge/embed-pending, and a chunk
-- without one is still findable by keyword — which is the half that matters for
-- the exact-term questions above.
-- =============================================================================

